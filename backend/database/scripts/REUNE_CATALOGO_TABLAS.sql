-- ============================================================================
-- Catálogo exclusivo REUNE (productos y causas independientes de REDECO)
-- Ejecutar con el esquema correspondiente (ej. ESIACOM).
-- Catálogo oficial CONDUSEF — última actualización: 01/04/2023
-- ============================================================================

CREATE TABLE REUNE_PRODUCTOS (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORIA       VARCHAR2(100) NOT NULL,
    NOMBRE          VARCHAR2(200) NOT NULL,
    NOMBRE_CORTO    VARCHAR2(100) NOT NULL,
    CODIGO_PRODUCTO VARCHAR2(20)  NOT NULL,
    ACTIVO          NUMBER(1)     DEFAULT 1 NOT NULL
);

CREATE UNIQUE INDEX UK_REUNE_PROD_CODIGO ON REUNE_PRODUCTOS (CODIGO_PRODUCTO);

COMMENT ON TABLE REUNE_PRODUCTOS IS 'Catálogo de productos/servicios REUNE (CONDUSEF)';

CREATE TABLE REUNE_CAUSAS (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCTO_ID     NUMBER        NOT NULL,
    DESCRIPCION     VARCHAR2(500) NOT NULL,
    CODIGO_CAUSA    VARCHAR2(10)  NOT NULL,
    CONSULTA        NUMBER(1)     DEFAULT 0 NOT NULL,
    RECLAMACION     NUMBER(1)     DEFAULT 0 NOT NULL,
    ACLARACION      NUMBER(1)     DEFAULT 0 NOT NULL,
    ACTIVO          NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT FK_REUNE_CAUSAS_PROD FOREIGN KEY (PRODUCTO_ID)
        REFERENCES REUNE_PRODUCTOS (ID)
);

CREATE INDEX IDX_REUNE_CAUSAS_PRODUCTO ON REUNE_CAUSAS (PRODUCTO_ID);
CREATE UNIQUE INDEX UK_REUNE_CAUSA_PROD ON REUNE_CAUSAS (PRODUCTO_ID, CODIGO_CAUSA);

COMMENT ON TABLE REUNE_CAUSAS IS 'Catálogo de causas REUNE por producto (CONDUSEF)';
